import { test, expect, type Page } from "@playwright/test";
import { readFile } from "node:fs/promises";
import { projectSchema, uid, type MaterialId, type Project } from "../../src/model";
import { CURRENT_DRAFT_KEY } from "../../src/drafts";
import { bom } from "../../src/engine";
import { addFramingLumber } from "../helpers/materialPlacement";

async function draft(page: Page, predicate: (project: Project) => boolean) {
  let actual: Project | null = null;
  await expect.poll(async () => {
    const raw = await page.evaluate(key => localStorage.getItem(key), CURRENT_DRAFT_KEY);
    actual = raw ? projectSchema.parse(JSON.parse(raw).project) : null;
    return actual !== null && predicate(actual);
  }).toBe(true);
  return actual!;
}
async function download(page: Page, name: RegExp) {
  await page.getByRole("button", { name: "Export", exact: true }).click();
  const pending = page.waitForEvent("download");
  await page.getByRole("dialog").getByRole("button", { name }).click();
  const file = await (await pending).path();
  if (!file) throw Error("Missing exported file");
  const text = await readFile(file, "utf8");
  await page.getByRole("button", { name: "Close dialog", exact: true }).click();
  return text;
}
async function importProject(page: Page, project: Project) {
  await page.goto("/");
  await page.getByRole("button", { name: "Open project", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByRole("button", { name: "Import a plan", exact: true }).click();
  await dialog.locator("input[type=file]").first().setInputFiles({ name: "synthetic-source-layout.yardwork.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(project)) });
  await expect(dialog).toHaveCount(0);
  return draft(page, actual => actual.name.startsWith(project.name) && actual.pieces.length === project.pieces.length);
}
async function openSource(page: Page, materialId: MaterialId, sourceId: string, state = "planar") {
  await page.getByRole("button", { name: "List", exact: true }).click();
  const row = page.locator(`.inspector-scroll .bom-row[data-stock-material="${materialId}"]`);
  await expect(row).toHaveCount(1);
  const disclosure = row.locator("details.recorded-source-layout").filter({ has: page.locator(`[data-source-id='${sourceId}']`) });
  await expect(disclosure).toHaveCount(1);
  if (await disclosure.getAttribute("open") === null) await disclosure.locator(":scope > summary").click();
  const layout = disclosure.locator(`.cut-stock-layout[data-source-id='${sourceId}']`);
  await expect(layout).toHaveAttribute("data-layout-state", state);
  await layout.scrollIntoViewIfNeeded();
  return { row, layout };
}

test("angle a board, reuse the shaped offcut, and reopen one recorded source", async ({ page }, info) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/");
  await page.getByRole("button", { name: "Rename project", exact: true }).click();
  await page.getByLabel("Project name", { exact: true }).fill(`Miter test ${uid().slice(0, 8)}`);
  await page.getByRole("button", { name: "Close dialog", exact: true }).click();
  await addFramingLumber(page);
  const initial = await draft(page, (project) => project.pieces.length === 1);
  await page.getByRole("button", { name: "Cut part", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByRole("button", { name: "Angled cut", exact: true }).click();
  await dialog.getByLabel("Left edge mark units", { exact: true }).selectOption("ft");
  await dialog.getByRole("spinbutton", { name: "Left edge mark", exact: true }).fill("3");
  await dialog.getByRole("spinbutton", { name: "Right edge mark", exact: true }).fill("39.5");
  await expect(dialog.getByTestId("angled-cut-line")).toBeVisible();
  const apply = dialog.getByRole("button", { name: "Apply angled cut", exact: true });
  await expect(apply).toBeEnabled();
  await expect(dialog.getByText("45° from square.", { exact: true })).toBeVisible();
  await page.screenshot({ path: info.outputPath("desktop-miter-preview.png"), animations: "disabled" });
  await apply.click();
  const cut = await draft(page, (project) => project.pieces.length === 2);
  const kept = cut.pieces.find(({ offcut }) => !offcut)!;
  const spare = cut.pieces.find(({ offcut }) => offcut)!;
  expect(kept.id).toEqual(initial.pieces[0].id);
  expect(kept.cutStock!.id).toEqual(spare.cutStock!.id);
  expect(kept.cutPlanes).toHaveLength(1);
  expect(spare.cutPlanes).toHaveLength(1);
  await page.getByRole("button", { name: "Cut pool (1)", exact: true }).click();
  await page.getByRole("button", { name: "Reuse O001", exact: true }).click();
  const reused = await draft(page, (project) => project.pieces.every(({ offcut }) => !offcut));
  expect(reused.pieces.find(({ id }) => id === spare.id)?.cutPlanes).toEqual(spare.cutPlanes);
  expect(bom(reused).find(({ id }) => id === "stud")?.physicalStockUnits).toEqual(1);

  const { row, layout } = await openSource(page, kept.material, kept.cutStock!.id, "profile-review");
  await expect(row).toContainText("1 board");
  await expect(layout.getByRole("img", { name: "Retained shapes across the stock face" })).toBeVisible();
  await expect(layout.getByRole("img", { name: "Retained shapes across the stock edge" })).toBeVisible();
  const markdown = await download(page, /^Build guide/);
  expect(markdown).toContain("45° from square");
  expect(markdown).toContain("Crosscut angled ends on lumber");
  expect(markdown).toContain("The retained solids leave the modeled saw gap");
  const exported = projectSchema.parse(JSON.parse(await download(page, /^Editable project/)));
  expect(exported.pieces).toEqual(reused.pieces);
  await page.getByRole("button", { name: "Save project", exact: true }).click();
  await expect.poll(async () => {
    const response = await page.request.get(`/api/projects/${reused.id}`);
    return response.ok() && JSON.stringify((await response.json()).project.pieces) === JSON.stringify(reused.pieces);
  }).toBe(true);
  await page.reload();
  await page.getByRole("button", { name: "Open project", exact: true }).click();
  await page.locator(".project-list > button").filter({ hasText: reused.name }).click();
  const reopened = await draft(page, (project) => project.id === reused.id && project.pieces.length === 2);
  expect(reopened.pieces).toEqual(reused.pieces);
  await importProject(page, exported);
  const imported = await draft(page, (project) => project.id !== reused.id && project.name.endsWith(" · imported"));
  expect(imported.pieces).toEqual(reused.pieces);
  expect(bom(imported).find(({ id }) => id === "stud")?.physicalStockUnits).toEqual(1);
  expect(errors).toEqual([]);
});

