test("phone plywood length-and-width cuts show three exact regions from one sheet", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto("/");
  await page.getByRole("button", { name: "Add 23/32 in BC pine plywood", exact: true }).click();
  const added = await draft(page, project => project.pieces.length === 1), id = added.pieces[0].id;
  await page.getByRole("button", { name: "Cut part", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("Retained length units", { exact: true }).selectOption("ft");
  await dialog.getByRole("spinbutton", { name: "Retained length", exact: true }).fill("5");
  await dialog.getByRole("spinbutton", { name: "Retained width", exact: true }).fill("20");
  await dialog.getByRole("button", { name: "Apply cuts", exact: true }).click();
  const cut = await draft(page, project => project.pieces.length === 3), piece = cut.pieces.find(piece => piece.id === id)!;
  expect(piece.size).toEqual([20, 0.703, 60]);
  expect(cut.pieces.filter(piece => piece.offcut)).toHaveLength(2);
  const sourceId = piece.cutStock!.id;
  const { row, layout } = await openSource(page, piece.material, sourceId);
  await expect(row).toContainText("1 sheet");
  // This exact panel's listed actual blank differs from its nominal 4x8 label.
  await expect(layout).toHaveAttribute("data-source-size", "[47.938,0.703,95.938]");
  const diagram = layout.locator("svg");
  await expect(diagram.locator("g[data-part-id]")).toHaveCount(3);
  const actual = await diagram.locator("g[data-part-id]").evaluateAll(nodes => nodes.map(node => ({ id: node.getAttribute("data-part-id"), size: JSON.parse(node.getAttribute("data-region-size")!), offset: JSON.parse(node.getAttribute("data-source-offset")!), offcut: node.getAttribute("data-offcut") === "true" })));
  expect(actual.find(row => row.id === id)).toMatchObject({ size: [20, 0.703, 60], offset: [0, 0, 0], offcut: false });
  const lengthOffcut = actual.find(row => row.offcut && row.offset[2] === 60.125)!;
  const widthOffcut = actual.find(row => row.offcut && row.offset[0] === 20.125)!;
  expect(lengthOffcut.offset).toEqual([0, 0, 60.125]);
  expect(lengthOffcut.size[0]).toBe(47.938);
  expect(lengthOffcut.size[1]).toBe(0.703);
  expect(lengthOffcut.size[2]).toBeCloseTo(35.813, 9);
  expect(widthOffcut.offset).toEqual([20.125, 0, 0]);
  expect(widthOffcut.size[0]).toBeCloseTo(27.813, 9);
  expect(widthOffcut.size.slice(1)).toEqual([0.703, 60]);
  await expect(diagram.locator("g[data-gap-index]")).toHaveCount(2);
  await diagram.scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: test.info().outputPath("phone-recorded-plywood-two-axis-cuts.png"), fullPage: false, animations: "disabled" });
  expect(bom(cut).find(row => row.id === piece.material)?.quantity).toBe(1);
  expect(await draft(page, actual => actual.id === cut.id)).toEqual(cut);
  expect(projectSchema.parse(JSON.parse(await download(page, /^Editable project/)))).toEqual(cut);
  expect(errors).toEqual([]);
});
