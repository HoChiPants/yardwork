test("phone bevel keeps the far end, rejects equal marks and keeps canceled stock intact", async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/");
  await page.getByRole("button", { name: "Add 23/32 in BC pine plywood", exact: true }).click();
  const original = await draft(page, (project) => project.pieces.length === 1);
  const cutButton = page.getByRole("button", { name: "Cut part", exact: true });
  const dialog = page.getByRole("dialog");
  const adjust = async () => {
    await cutButton.click();
    await dialog.getByRole("button", { name: "Angled cut", exact: true }).click();
    await dialog.getByRole("combobox", { name: "Mark across", exact: true }).selectOption("thickness");
    await dialog.getByRole("combobox", { name: "Keep piece", exact: true }).selectOption("end");
    await dialog.getByRole("spinbutton", { name: "Left edge mark", exact: true }).fill("40");
    await dialog.getByRole("spinbutton", { name: "Right edge mark", exact: true }).fill("40");
    await expect(dialog.getByRole("alert")).toContainText("two different edge marks");
    await expect(dialog.getByRole("button", { name: "Apply angled cut" })).toBeDisabled();
    await dialog.getByRole("spinbutton", { name: "Right edge mark", exact: true }).fill("40.5");
    await expect(dialog.getByRole("button", { name: "Apply angled cut" })).toBeEnabled();
  };
  await adjust();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("phone-bevel-preview.png"), animations: "disabled" });
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click();
  expect(await draft(page, (project) => project.id === original.id)).toEqual(original);
  await adjust();
  await dialog.getByRole("button", { name: "Apply angled cut" }).click();
  const actual = await draft(page, (project) => project.pieces.length === 2);
  const kept = actual.pieces.find(({ id }) => id === original.pieces[0].id)!;
  expect(kept.cutStock!.offset[2]).toBeGreaterThan(40);
  expect(kept.cutPlanes[0].normal[1]).toBeGreaterThan(0);
  expect(bom(actual).find(({ id }) => id === "plytanium-703")?.physicalStockUnits).toBe(1);
});

